/**
 * Адрес документации API в браузере.
 *
 * Swagger/Scalar монтируется самим Api и только в Development (`app.Environment.IsDevelopment()`
 * в `Program.cs`): в «проде» это анонимный доступ ко всей поверхности API, поэтому в проде
 * маршрутов нет вовсе. Отсюда два следствия, из-за которых адрес — конфигурация, а не константа:
 *
 *   1. в проде ссылка обязана исчезнуть, а не вести на 404 (и уж точно не на `localhost`,
 *      который у пользователя указывает на его собственную машину);
 *   2. префикс зависит от того, как открыт фронт: через dev-сервер Vite браузер обращается
 *      к Api напрямую (двойной пробег через прокси не нужен), а через контейнер `web` —
 *      тем же источником, что и остальной фронт, то есть через nginx контейнера.
 *
 * Задаётся на этапе сборки SPA (`deploy/Dockerfile.web`, build-arg `VITE_API_DOCS_PATH`).
 * Пустое значение — ссылки нет вовсе.
 */
const rawPath = import.meta.env.VITE_API_DOCS_PATH?.trim() ?? ''

/** Путь к документации API без завершающего слэша; пустая строка означает «ссылки нет». */
export const apiDocsPath = rawPath.replace(/\/+$/, '')

/**
 * Демо-учётка стенда: подставляется в форму входа, чтобы стенд открывался в один клик.
 *
 * Api создаёт эту учётку только в Development (`SeedOnStart`), а вне Development **падает
 * на старте**, если сид включён: пароль известен из исходников. Значит, предзаполнять форму
 * можно ровно там, где учётка существует. Признак ровно тот же, что у ссылки на документацию
 * API (`lib/env.ts`): она тоже появляется только в Development. Отдельный флаг сборки был бы
 * вторым источником правды об одном и том же — «это Development-стенд».
 *
 * Без предзаполнения пользователь «прода» получал бы поле «Пароль», заполненное паролем
 * чужой учётки, и кнопку «Войти» с заведомо неверными данными.
 *
 * Условие проверки `import.meta.env.VITE_API_DOCS_PATH` буквально (а не через
 * `apiDocsPath` из `lib/env.ts`) — это не дублирование ради дублирования, а условие
 * корректности: Vite подставляет значение на этапе сборки, и при пустом значении условие
 * сворачивается в константу, после чего минификатор вырезает ветку вместе со строкой
 * пароля. Через промежуточную переменную свёртка не срабатывает, и пароль остаётся в
 * прод-бандле мёртвым, но читаемым текстом (проверено сборкой: при пустом значении строк
 * `demo-password`/`demo@pingboard` в `dist/assets/*.js` нет).
 */
export const demoCredentials = (import.meta.env.VITE_API_DOCS_PATH ?? '').trim()
  ? { email: 'demo@pingboard.local', password: 'demo-password' }
  : null

namespace Pingboard.Application.Abstractions;

/// <summary>
///     Один сегмент полосы доступности в терминах БД: номер сегмента в окне и счётчики
///     проверок в нём. Именно агрегат, а не сами проверки: полоса по умолчанию — 24 сегмента
///     за 24 часа, а проверок за это время может быть 8640 (интервал 10 с) — подтягивать их
///     в память только ради 24 чисел незачем.
/// </summary>
public sealed record CheckBucket(int Index, int Total, int Failed);
